-- Baseline for local development: the `events` table as it was before the country column.
--
-- The table was created in the Supabase dashboard, so no migration made it. This file
-- recreates it for a local stack (`supabase start`, `supabase test db`), so the later
-- migrations and the tests can run. On the live project the table already exists and
-- every statement here is skipped.

create table if not exists public.events (
  id bigint generated by default as identity primary key,
  name text not null,
  location text not null,
  "dateStart" date not null,
  "dateEnd" date not null,
  link text not null default ''
);

alter table public.events enable row level security;

do $$
begin
  if not exists (
    select 1 from pg_policies
    where schemaname = 'public' and tablename = 'events' and policyname = 'Enable read access for all users'
  ) then
    create policy "Enable read access for all users" on public.events for select using (true);
  end if;
end
$$;
