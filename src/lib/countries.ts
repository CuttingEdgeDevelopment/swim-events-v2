/**
 * ISO alpha-3 codes that are easily typed instead of the IOC code ("MCO" for Monaco is
 * "MON"). Mirrors the `country_aliases` table in Supabase.
 */
export const COUNTRY_ALIASES: Record<string, string> = {
  BGR: 'BUL',
  CHE: 'SUI',
  DEU: 'GER',
  DNK: 'DEN',
  GRC: 'GRE',
  HRV: 'CRO',
  MCO: 'MON',
  NLD: 'NED',
  PRT: 'POR',
  SVN: 'SLO',
}

/** The IOC code for a stored code, with aliases resolved, or null when it's unknown. */
export function countryCode(code: string | null | undefined): string | null {
  const upper = code?.trim().toUpperCase() ?? ''
  const resolved = COUNTRY_ALIASES[upper] ?? upper
  return Object.hasOwn(COUNTRIES, resolved) ? resolved : null
}
